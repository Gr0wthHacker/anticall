"""Optional docker compose override: mounts your generated pjsip file into the harness."""

from __future__ import annotations


def render_compose_override(pjsip_path: str, *, publish_sip: bool = False) -> str:
    """Return YAML text (plain template, no YAML library needed).

    SIP is NOT published to the network unless ``publish_sip`` is True; even then it binds
    to 127.0.0.1. Expose it publicly only behind a firewall limited to your provider.
    """
    if any(ch in pjsip_path for ch in "\r\n\"'"):
        raise ValueError("pjsip_path contains unsafe characters")
    lines = [
        "# Generated by `callshield init`. Use with:",
        "#   docker compose -f infra/docker/docker-compose.yml -f compose.override.yml \\",
        "#     --profile asterisk up",
        "# UNVERIFIED: the compose files have not been exercised against a real trunk.",
        "services:",
        "  asterisk:",
        "    volumes:",
        f'      - "{pjsip_path}:/etc/asterisk/pjsip.conf:ro"',
    ]
    if publish_sip:
        lines += ["    ports:", '      - "127.0.0.1:5060:5060/udp"']
    return "\n".join(lines) + "\n"
