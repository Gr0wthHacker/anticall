"""Pure renderer: provider profile + user inputs -> pjsip.conf trunk section.

Output may contain the SIP password. Callers write it only to a local file via
``providers.secret_io.write_private_file`` and never print or log it.
"""

from __future__ import annotations

import re
from collections.abc import Mapping

from callshield.providers.base import UNVERIFIED_BANNER, ProviderProfile

_NAME = re.compile(r"^[A-Za-z0-9_-]{1,40}$")
_HOST = re.compile(r"^[A-Za-z0-9._:\[\]-]{1,253}$")
_PLACEHOLDER = "CHANGE_ME"


class RenderInputError(ValueError):
    """User input that cannot be safely written into a config file."""


def _value(inputs: Mapping[str, str], key: str, default: str = "") -> str:
    raw = str(inputs.get(key, default) or default).strip()
    if any(ch in raw for ch in "\r\n;\x00"):
        raise RenderInputError(f"{key}: newline, ';' and NUL are not allowed")
    return raw


def _port(inputs: Mapping[str, str], profile: ProviderProfile) -> int:
    raw = _value(inputs, "sip_port", str(profile.sip_port))
    if not raw.isdigit() or not 1 <= int(raw) <= 65535:
        raise RenderInputError("sip_port must be 1-65535")
    return int(raw)


def _auth_mode(inputs: Mapping[str, str], profile: ProviderProfile) -> str:
    fallback = profile.auth_style if profile.auth_style in ("registration", "ip_auth") else ""
    mode = _value(inputs, "auth_mode", fallback or "registration")
    if mode not in ("registration", "ip_auth"):
        raise RenderInputError("auth_mode must be 'registration' or 'ip_auth'")
    return mode


def _header(profile: ProviderProfile, mode: str) -> list[str]:
    lines = [
        f"; CallShield trunk: profile={profile.id} auth={mode}",
        "; Generated by `callshield init`. Contains secrets: keep this file private (0600).",
    ]
    if not profile.verified:
        lines.append(f"; {UNVERIFIED_BANNER}")
    if profile.acceptable_use_url:
        lines.append(f"; Read the provider's acceptable-use terms: {profile.acceptable_use_url}")
    att = profile.attestation
    lines.append(
        f"; Attestation source (UNVERIFIED): {att.source} {att.header_name}".rstrip()
        + f"; outbound A attestation: {profile.supports_outbound_a_attestation}"
    )
    lines.append(f"; Inbound DID is read from: {profile.did_source} {profile.did_header}".rstrip())
    return lines


def _endpoint(name: str, transport: str, context: str, codecs: str, mode: str) -> list[str]:
    lines = [
        f"[{name}]",
        "type=endpoint",
        f"transport={transport}",
        f"context={context}",
        "disallow=all",
        f"allow={codecs}",
        f"aors={name}",
        "direct_media=no",
        "rtp_symmetric=yes",
        "force_rport=yes",
        "rewrite_contact=yes",
    ]
    if mode == "registration":
        lines.append(f"outbound_auth={name}-auth")
    return lines


def _registration(name: str, transport: str, host: str, port: int, user: str, pw: str) -> list[str]:
    return [
        f"[{name}-auth]",
        "type=auth",
        "auth_type=userpass",
        f"username={user or _PLACEHOLDER}",
        f"password={pw or _PLACEHOLDER}",
        "",
        f"[{name}-reg]",
        "type=registration",
        f"transport={transport}",
        f"outbound_auth={name}-auth",
        f"server_uri=sip:{host}:{port}",
        f"client_uri=sip:{user or _PLACEHOLDER}@{host}:{port}",
        "retry_interval=60",
        "expiration=3600",
        "",
    ]


def _transport_block(transport_name: str, protocol: str, external_ip: str) -> list[str]:
    lines = [f"[{transport_name}]", "type=transport", f"protocol={protocol}", "bind=127.0.0.1:5060"]
    if external_ip:
        lines += [
            f"external_media_address={external_ip}",
            f"external_signaling_address={external_ip}",
        ]
    else:
        lines.append("; Behind NAT? add external_media_address / external_signaling_address.")
    lines.append("; Bind 0.0.0.0 only when the provider must reach you AND a firewall limits it.")
    return [*lines, ""]


def render_pjsip(profile: ProviderProfile, supplied: Mapping[str, str]) -> str:
    """Return the pjsip.conf trunk section for ``profile`` using the user's inputs."""
    user_inputs = {s.key: s.default for s in profile.required_inputs if s.default} | dict(supplied)
    name = _value(user_inputs, "trunk_name", "trunk")
    if not _NAME.match(name):
        raise RenderInputError("trunk_name may use letters, digits, '-' and '_' only")
    host = _value(user_inputs, "sip_host", profile.sip_host) or _PLACEHOLDER
    if not _HOST.match(host):
        raise RenderInputError("sip_host contains invalid characters")
    mode = _auth_mode(user_inputs, profile)
    transport_name = _value(user_inputs, "transport_name", "transport-callshield")
    context = _value(user_inputs, "inbound_context", "from-trunk")
    codecs = ",".join(profile.codecs)
    match = _value(user_inputs, "ip_auth_match", "") or host
    lines = _header(profile, mode)
    lines.append("")
    if _value(user_inputs, "include_transport", "false") == "true":
        proto = "udp" if profile.transport == "tls" else profile.transport
        lines += _transport_block(transport_name, proto, _value(user_inputs, "external_ip"))
    if mode == "registration":
        port = _port(user_inputs, profile)
        user = _value(user_inputs, "username")
        lines += _registration(
            name, transport_name, host, port, user, _value(user_inputs, "password")
        )
    lines += _endpoint(name, transport_name, context, codecs, mode)
    lines += ["", f"[{name}]", "type=aor", f"contact=sip:{host}:{_port(user_inputs, profile)}", ""]
    lines += [f"[{name}]", "type=identify", f"endpoint={name}", f"match={match}", ""]
    return "\n".join(lines)
