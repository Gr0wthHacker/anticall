"""Generate docs/deployment/configuration-reference.md and env.example from the settings."""

from __future__ import annotations

from pathlib import Path

from callshield.configreg.registry import ConfigRow, all_rows
from callshield.providers.render_env import render_env_example

GROUP_TITLES = {
    "Settings": "Core",
    "CallbackSettings": "Callback flow",
    "LLMSettings": "LLM (optional)",
    "InstanceSettings": "Instance (written by `callshield init`)",
    "AsteriskSettings": "Asterisk telephony (ARI)",
    "VoiceSettings": "Voice engines",
}
TABLE_HEAD = "| Variable | Type | Default | Range | Who may change | Related gate | Description |"
HEADER = """# Configuration reference

<!-- GENERATED by apps/api/scripts/gen_config_reference.py. Do not edit by hand. -->

Every environment variable the software reads, generated from the settings classes. A test
fails if this file is stale. Regenerate with:

```bash
cd apps/api && .venv/Scripts/python scripts/gen_config_reference.py --write
```

Settings are read from the process environment and from `.env` in the working directory.
**Every risky capability defaults to off.** "Related gate" names an item in
[`docs/legal/release-gates.md`](../legal/release-gates.md); turning a switch on does not clear
that gate. Callback ranges are hard ceilings: values above them are rejected at startup.
"""


def _cell(text: str) -> str:
    return (text or "-").replace("|", r"\|")


def _row_line(row: ConfigRow) -> str:
    cells = [
        f"`{row.env}`",
        row.type_name,
        f"`{row.default}`" if row.default else "-",
        row.range_text,
        row.who,
        row.gate,
        row.description,
    ]
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def build_reference() -> str:
    rows = all_rows()
    lines = [HEADER]
    group = ""
    for row in rows:
        if row.group != group:
            group = row.group
            lines += [
                "",
                f"## {GROUP_TITLES.get(group, group)}",
                "",
                TABLE_HEAD,
                "|---|---|---|---|---|---|---|",
            ]
        lines.append(_row_line(row))
    return "\n".join(lines) + "\n"


def repo_root() -> Path:
    return Path(__file__).resolve().parents[5]


def reference_path() -> Path:
    return repo_root() / "docs" / "deployment" / "configuration-reference.md"


def env_example_path() -> Path:
    return repo_root() / "env.example"


def stale_files() -> list[Path]:
    stale: list[Path] = []
    for path, expected in (
        (reference_path(), build_reference()),
        (env_example_path(), render_env_example()),
    ):
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            stale.append(path)
    return stale
