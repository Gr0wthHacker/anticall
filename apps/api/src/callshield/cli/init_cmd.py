"""`callshield init`: wizard or --non-interactive --answers file -> .env, pjsip, report."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from pydantic import ValidationError
from sqlalchemy.orm import Session

from callshield.cli.admin_service import AdminCreateError, create_admin
from callshield.cli.answers import (
    Answers,
    AnswersError,
    answers_from_dict,
    answers_to_env,
    validate_answers,
)
from callshield.cli.context import CliContext
from callshield.cli.db_cmd import upgrade_database
from callshield.cli.out import err, out
from callshield.cli.report import render_report
from callshield.cli.wizard import run_wizard
from callshield.db.session import make_engine, make_session_factory, session_scope
from callshield.doctor.loader import load_config
from callshield.doctor.model import safe_validation_message
from callshield.providers.base import ProviderProfile
from callshield.providers.registry import get_profile
from callshield.providers.render_compose import render_compose_override
from callshield.providers.render_env import render_env
from callshield.providers.render_pjsip import RenderInputError, render_pjsip
from callshield.providers.secret_io import write_private_file

ARI_CONF_TEMPLATE = (
    "; Generated by callshield init. Contains the ARI password: keep private.\n"
    "[general]\nenabled=yes\npretty=no\nallowed_origins=http://127.0.0.1:8000\n\n"
    "[{user}]\ntype=user\nread_only=no\npassword={password}\npassword_format=plain\n"
)


def register(sub: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
    p = sub.add_parser("init", help="create .env, pjsip snippet and a setup report")
    p.add_argument("--non-interactive", action="store_true")
    p.add_argument("--answers", help="JSON answers file (with --non-interactive)")
    p.add_argument("--output-dir", default=".", help="where to write files (default: here)")
    p.add_argument("--force", action="store_true", help="overwrite an existing .env")
    p.add_argument("--with-compose-override", action="store_true")


def _collect(args: argparse.Namespace, ctx: CliContext) -> Answers:
    if args.non_interactive:
        if not args.answers:
            raise AnswersError("--non-interactive needs --answers FILE")
        data = json.loads(Path(args.answers).read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            raise AnswersError("answers file must be a JSON object")
        return answers_from_dict(data)
    return run_wizard(ctx)


def _trunk_name(profile: ProviderProfile, ans: Answers) -> str:
    default = next((s.default for s in profile.required_inputs if s.key == "trunk_name"), "trunk")
    return ans.provider_inputs.get("trunk_name") or default


def _write_all(
    ans: Answers, profile: ProviderProfile, out_dir: Path, ctx: CliContext, extras: bool
) -> list[str]:
    trunk = _trunk_name(profile, ans)
    pjsip_name = "pjsip.callshield.conf"
    env = answers_to_env(ans, ctx.new_secret, trunk)
    env["CALLSHIELD_INSTANCE_PJSIP_PATH"] = str((out_dir / pjsip_name).resolve())
    inputs = {
        **{s.key: s.default for s in profile.required_inputs if s.default},
        **ans.provider_inputs,
    }
    write_private_file(out_dir / ".env", render_env(env))
    write_private_file(out_dir / pjsip_name, render_pjsip(profile, inputs))
    ari_conf = ARI_CONF_TEMPLATE.format(
        user=ans.ari_username, password=env["CALLSHIELD_ASTERISK_ARI_PASSWORD"]
    )
    write_private_file(out_dir / "ari.callshield.conf", ari_conf)
    files = [".env", pjsip_name, "ari.callshield.conf"]
    if extras:
        write_private_file(out_dir / "compose.override.yml", render_compose_override(pjsip_name))
        files.append("compose.override.yml")
    (out_dir / "SETUP_REPORT.md").write_text(
        render_report(ans, profile, [*files, "SETUP_REPORT.md"]), encoding="utf-8"
    )
    return [*files, "SETUP_REPORT.md"]


def _bootstrap_admin(ans: Answers, out_dir: Path) -> str:
    """Upgrade the DB and create the admin. Returns a status line (no secrets)."""
    cfg = load_config(out_dir / ".env")
    upgrade_database(cfg.settings.db_url)
    engine = make_engine(cfg.settings.db_url)
    try:
        with session_scope(make_session_factory(engine)) as session:
            _create(session, ans)
    finally:
        engine.dispose()
    return f"admin {ans.admin_email} created"


def _create(session: Session, ans: Answers) -> None:
    create_admin(session, ans.tenant_name, ans.admin_email, ans.admin_password)


def run(args: argparse.Namespace, ctx: CliContext) -> int:
    out_dir = Path(args.output_dir)
    if (out_dir / ".env").exists() and not args.force:
        err(f"{out_dir / '.env'} exists; refusing to overwrite secrets. Use --force.")
        return 2
    try:
        ans = _collect(args, ctx)
        validate_answers(ans)
        profile = get_profile(ans.provider_profile)
        files = _write_all(ans, profile, out_dir, ctx, args.with_compose_override)
        load_config(out_dir / ".env")  # fail loudly if what we wrote does not load
        status = _bootstrap_admin(ans, out_dir) if ans.admin_email and ans.admin_password else ""
    except (AnswersError, RenderInputError, AdminCreateError, OSError, ValueError) as exc:
        err(f"init failed: {exc}")
        return 2
    except ValidationError as exc:
        err("init wrote an invalid config: " + safe_validation_message(exc))
        return 2
    out("Wrote: " + ", ".join(files))
    if status:
        out(status)
    out(f"Gated features ON: {', '.join(ans.enabled_keys()) or 'none'}")
    out("Next: callshield doctor")
    return 0
